export function useDeliveryZone() {
  function getZone(region: string): DeliveryZone | null {
    if (!region?.trim()) return null
    const r = region.toLowerCase()
    for (const [key, zone] of Object.entries(REGION_NAME_ZONE)) {
      if (r.includes(key.toLowerCase())) return zone as DeliveryZone
    }
    return null
  }

  return { getZone, ZONE_CONFIG }
}
